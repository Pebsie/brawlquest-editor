// Headless click-through of Quest Studio's Quick quest on a real bq-content.db.
//   python3 -m http.server 8981 --bind 127.0.0.1 &   (in this folder), then
//   DB=/path/bq-content.db OUT=/tmp/qq- node tests/headless-quick-quest.mjs
import fs from "fs";
const { chromium } = await import("/usr/local/lib/pnpm/5/.pnpm/playwright-core@1.59.1/node_modules/playwright-core/index.mjs");
const URL = process.env.URL || "http://127.0.0.1:8981/index.html", DB = process.env.DB || "/workspace/questux/bq-content.db", OUT = process.env.OUT || "/workspace/lore/screens/questux-after-";
const W = +(process.env.W || 1500), H = +(process.env.H || 920);
const b = await chromium.launch({ executablePath: "/usr/bin/google-chrome" });
const p = await (await b.newContext({ viewport: { width: W, height: H } })).newPage();
const errs = []; p.on("pageerror", e => errs.push("pageerror " + e.stack)); p.on("console", m => { if (m.type() === "error" && !/404/.test(m.text())) errs.push("console " + m.text()); });
p.on("dialog", d => d.accept());
const ok = (c, m) => { console.log((c ? "ok: " : "FAIL: ") + m); if (!c) process.exitCode = 1; };
const wait = ms => p.waitForTimeout(ms);
const shot = n => p.screenshot({ path: OUT + n + ".png" });
await p.goto(URL);
await p.setInputFiles("#open", DB);
await p.waitForFunction(() => typeof S !== "undefined" && S.c && S.c.quests); await wait(500);
const before = await p.evaluate(() => S.c.quests.length);
const issues0 = await p.evaluate(() => BQCheck.run(BQ.query).errors.length);
await p.evaluate(() => { location.hash = "#studio/quick"; }); await wait(800);
await p.waitForSelector(".qq-pc[data-npc]", { timeout: 15000 }); await wait(600);
ok(await p.$$eval(".qq-card", x => x.length) === 1, "starts with one question: who gives it");
await shot("1-who");
const fred = await p.evaluate(() => S.c.npcs.find(n => n.Name === "Bartender Fred").id);
await p.click(`.qq-pc[data-npc="${fred}"]`); await wait(400);
ok(await p.$eval(".qq-card[data-card=giver] .qq-sum", e => e.textContent.includes("Bartender Fred")), "giver card folds to one line");
await shot("2-what");
await p.click('.qq-type[data-type="kill"]'); await wait(400);
await shot("3-pick-enemy");
const nearMob = await p.$eval(".qq-pick .qq-pc.mob", e => e.dataset.mob);
await p.click(`.qq-pick .qq-pc.mob[data-mob="${nearMob}"]`); await wait(300);
const count = await p.evaluate(() => QQ.st.objs[0].count);
ok(count >= 3 && count <= 10, `kill count suggested from how many live nearby: ${count} ${nearMob}`);
await p.click('.qq-count button:has-text("+")'); await wait(200);
ok(await p.evaluate(c => QQ.st.objs[0].count === c + 1, count), "the + stepper raises the count");
await p.click("#qq-add"); await wait(200);
await p.click('.qq-type[data-type="collect"]'); await wait(300);
await shot("4-pick-item");
const item = await p.$eval(".qq-pick .qq-pc.item", e => +e.dataset.item);
await p.click(`.qq-pick .qq-pc.item[data-item="${item}"]`); await wait(300);
await shot("5-two-things");
await p.click("#qq-objs-ok"); await wait(300);
ok(await p.$$eval(".qq-card", x => x.length) === 3, "the words card opens after the objectives");
await p.fill('textarea[data-qq="Offer"]', "Spiders have got into the beer garden again and nobody will sit out there. Could you clear some out for me, and bring back what they drop so I can show the council?");
await p.fill('textarea[data-qq="Complete"]', "That's much better. Thank you. Here's what I said I'd pay.");
await shot("6-words");
await p.click("#qq-words-ok"); await wait(400);
ok(await p.$$eval(".qq-card", x => x.length) === 4, "hand-in and reward card shows");
const v = await p.evaluate(() => qqVals(QQ.st));
console.log("auto:", JSON.stringify(v));
ok(v.level >= 1 && v.XP > 0, "level, XP and gold filled in");
await shot("7-reward-and-preview");
await p.click(".qq-more summary"); await wait(200);
await p.evaluate(() => document.querySelector("#qq-flow").scrollTo(0, 99999)); await wait(200);
await shot("8-more-options");
// typing keeps the scroll where it is
const top = await p.$eval("#qq-flow", e => e.scrollTop);
await p.fill('input[data-qq="title"]', "Spiders in the Beer Garden");
ok(Math.abs((await p.$eval("#qq-flow", e => e.scrollTop)) - top) < 2, "typing the title doesn't move the scroll");
await p.click("#qq-make"); await wait(900);
const nq = await p.evaluate(() => S.c.quests.find(q => q.Title === "Spiders in the Beer Garden"));
ok(nq && nq.Giver === fred && nq.TurnIn === fred, "quest saved with giver and hand-in");
const steps = JSON.parse(nq.Steps);
console.log("row:", JSON.stringify({ id: nq.id, Zone: nq.Zone, Level: nq.Level, MinLevel: nq.MinLevel, XP: nq.XP, Gold: nq.Gold, Prereqs: nq.Prereqs, Rewards: nq.Rewards, Steps: steps }));
ok(steps.length === 2 && steps[0].Type === "kill" && steps[0].Target === nearMob && steps[1].Type === "collect" && steps[1].Consume === true, "two steps: kill and collect");
ok(nq.Complete.startsWith("That's much better") && nq.Offer.startsWith("Spiders have got"), "offer and hand-in lines saved");
ok(nq.Prereqs === "[]" && nq.Rewards === "[]", "no prerequisite and no item reward by default");
ok((await p.evaluate(() => S.c.quests.length)) === before + 1, "one quest added");
await shot("9-made");
ok((await p.evaluate(() => BQCheck.run(BQ.query).errors.length)) === issues0, "the save checks find no new errors");
await p.click("#qq-play"); await wait(1500);
await shot("10-play");
await p.click("#qs-prev-close"); await wait(200);
// undo removes it
await p.click("#qs-undo"); await wait(600);
ok(!(await p.evaluate(() => S.c.quests.some(q => q.Title === "Spiders in the Beer Garden"))), "undo removes the new quest");
await p.click("#qs-redo"); await wait(600);
ok(await p.evaluate(() => S.c.quests.some(q => q.Title === "Spiders in the Beer Garden")), "redo puts it back");
if (process.env.SAVE) { const bytes = await p.evaluate(() => Array.from(BQ.bytes())); fs.writeFileSync(process.env.SAVE, Buffer.from(bytes)); console.log("saved", process.env.SAVE); }
ok(!errs.length, "no page errors" + (errs.length ? ":\n" + errs.join("\n") : ""));
await b.close();
